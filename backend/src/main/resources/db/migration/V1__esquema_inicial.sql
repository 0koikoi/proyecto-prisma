    CONSTRAINT ck_order_details_price CHECK (unit_price >= 0 AND unit_price <> 'NaN'),
    CONSTRAINT ck_order_details_cost CHECK (unit_cost IS NULL OR (unit_cost >= 0 AND unit_cost <> 'NaN'))
