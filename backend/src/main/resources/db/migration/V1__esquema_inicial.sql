CREATE TABLE orders (
    id                       bigint        GENERATED BY DEFAULT AS IDENTITY,
    order_code               varchar(50)   NOT NULL,
    request_key              uuid          NOT NULL,
    created_by               bigint        NOT NULL,
    channel                  varchar(30)   NOT NULL,
    customer_name            varchar(120)  NOT NULL,
    customer_phone           varchar(25)   NOT NULL,
    shipping_address         text          NOT NULL,
    reference                text          NOT NULL,
    delivery_scope           varchar(15)   NOT NULL,
    courier_company          varchar(80),
    tracking_number          varchar(80),
    driver_name              varchar(100),
    driver_phone             varchar(25),
    vehicle_plate            varchar(15),
    shipping_evidence_key    text,
    requested_payment_method varchar(20)   NOT NULL,
    shipping_status          varchar(20)   NOT NULL DEFAULT 'PENDING',
    shipping_cost            numeric(12,2) NOT NULL DEFAULT 0,
    created_at               timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    shipped_at               timestamptz,
    delivered_at             timestamptz,
    notes                    text,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_orders_order_code UNIQUE (order_code),
    CONSTRAINT uq_orders_request_key UNIQUE (request_key),
    CONSTRAINT ck_orders_text_required CHECK (
        btrim(order_code) <> '' AND btrim(customer_name) <> '' AND btrim(customer_phone) <> ''
        AND btrim(shipping_address) <> '' AND btrim(reference) <> ''
    ),
    CONSTRAINT ck_orders_text_optional CHECK (
        (courier_company IS NULL OR btrim(courier_company) <> '')
        AND (tracking_number IS NULL OR btrim(tracking_number) <> '')
        AND (driver_name IS NULL OR btrim(driver_name) <> '')
        AND (driver_phone IS NULL OR btrim(driver_phone) <> '')
        AND (vehicle_plate IS NULL OR btrim(vehicle_plate) <> '')
        AND (shipping_evidence_key IS NULL OR btrim(shipping_evidence_key) <> '')
    ),
    CONSTRAINT ck_orders_channel CHECK (channel IN ('WHATSAPP', 'MESSENGER', 'INSTAGRAM', 'TIENDA_ONLINE')),
    CONSTRAINT ck_orders_delivery_scope CHECK (delivery_scope IN ('LOCAL', 'NATIONAL')),
    CONSTRAINT ck_orders_payment_method CHECK (requested_payment_method IN ('EFECTIVO', 'YAPE', 'PLIN', 'TARJETA')),
    CONSTRAINT ck_orders_shipping_status CHECK (
        shipping_status IN ('PENDING', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT ck_orders_shipping_cost CHECK (shipping_cost >= 0 AND shipping_cost <> 'NaN'),
    CONSTRAINT ck_orders_shipped_requires_date CHECK (
        shipping_status NOT IN ('SHIPPED', 'DELIVERED') OR shipped_at IS NOT NULL
    ),
    CONSTRAINT ck_orders_delivered_requires_date CHECK (
        shipping_status <> 'DELIVERED' OR delivered_at IS NOT NULL
    ),
    CONSTRAINT ck_orders_shipped_after_created CHECK (shipped_at IS NULL OR shipped_at >= created_at),
    CONSTRAINT ck_orders_delivered_after_shipped CHECK (
        delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at)
    )
);

CREATE INDEX ix_orders_status_created ON orders (shipping_status, created_at);
CREATE INDEX ix_orders_created_by ON orders (created_by);

