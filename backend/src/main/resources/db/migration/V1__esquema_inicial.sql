-- available_stock = stock físico - unidades con reserva ACTIVE.
CREATE VIEW v_inventory_availability AS
SELECT v.id AS variant_id,
       v.current_stock,
       COALESCE(r.reserved_stock, 0)                       AS reserved_stock,
       v.current_stock - COALESCE(r.reserved_stock, 0)     AS available_stock
FROM product_variants v
LEFT JOIN (
    SELECT od.variant_id, SUM(od.quantity)::integer AS reserved_stock
    FROM inventory_reservations ir
    JOIN order_details od ON od.id = ir.order_detail_id
    WHERE ir.status = 'ACTIVE'
    GROUP BY od.variant_id
) r ON r.variant_id = v.id;

-- Subtotales por línea.
CREATE VIEW v_sale_lines AS
SELECT d.id AS sale_detail_id, d.sale_id, d.variant_id, d.quantity, d.unit_price, d.unit_cost,
       d.quantity * d.unit_price AS subtotal
FROM sale_details d;

CREATE VIEW v_order_lines AS
SELECT d.id AS order_detail_id, d.order_id, d.variant_id, d.quantity, d.unit_price, d.unit_cost,
       d.quantity * d.unit_price AS subtotal
FROM order_details d;

CREATE VIEW v_purchase_lines AS
SELECT d.id AS purchase_detail_id, d.purchase_id, d.variant_id, d.quantity, d.unit_cost,
       d.quantity * d.unit_cost AS subtotal
FROM purchase_details d;

-- Totales por documento.
CREATE VIEW v_sales_totals AS
SELECT s.id AS sale_id,
       COALESCE(l.subtotal, 0)               AS subtotal,
       COALESCE(l.subtotal, 0) - s.discount  AS total
FROM sales s
LEFT JOIN (SELECT sale_id, SUM(subtotal) AS subtotal FROM v_sale_lines GROUP BY sale_id) l
       ON l.sale_id = s.id;

CREATE VIEW v_order_totals AS
SELECT o.id AS order_id,
       COALESCE(l.total_products, 0)                    AS total_products,
       COALESCE(l.total_products, 0) + o.shipping_cost  AS total_order
FROM orders o
LEFT JOIN (SELECT order_id, SUM(subtotal) AS total_products FROM v_order_lines GROUP BY order_id) l
       ON l.order_id = o.id;

CREATE VIEW v_purchase_totals AS
SELECT p.id AS purchase_id,
       ROUND(COALESCE(l.total, 0), 2) AS total
FROM purchases p
LEFT JOIN (SELECT purchase_id, SUM(subtotal) AS total FROM v_purchase_lines GROUP BY purchase_id) l
       ON l.purchase_id = p.id;

-- Neto cobrado por pedido
CREATE VIEW v_order_payment_summary AS
SELECT o.id AS order_id,
       COALESCE(SUM(CASE WHEN f.transaction_type = 'IN'  THEN f.amount
                         WHEN f.transaction_type = 'OUT' THEN -f.amount END), 0) AS net_paid
FROM orders o
LEFT JOIN financial_transactions f
       ON f.order_id = o.id AND f.status = 'VERIFIED'
GROUP BY o.id;

-- Estado de pago del pedido
CREATE VIEW v_order_payment_status AS
SELECT o.id AS order_id,
       t.total_products,
       t.total_order,
       p.net_paid,
       (p.net_paid >= t.total_products AND t.total_products > 0) AS products_paid,
       CASE
           WHEN o.shipping_status = 'CANCELLED' AND p.net_paid > 0  THEN 'REFUND_PENDING'
           WHEN o.shipping_status = 'CANCELLED'                      THEN 'NOT_APPLICABLE'
           WHEN p.net_paid <= 0                                      THEN 'PENDING'
           WHEN p.net_paid < t.total_order                           THEN 'PARTIAL'
           ELSE 'PAID'
       END AS payment_status
FROM orders o
JOIN v_order_totals t          ON t.order_id = o.id
JOIN v_order_payment_summary p ON p.order_id = o.id;

-- Efectivo esperado del turno de caja
CREATE VIEW v_cash_session_summary AS
SELECT c.id AS cash_register_id,
       c.initial_cash,
       COALESCE(m.cash_in, 0)  AS cash_in,
       COALESCE(m.cash_out, 0) AS cash_out,
       c.initial_cash + COALESCE(m.cash_in, 0) - COALESCE(m.cash_out, 0) AS expected_cash
FROM cash_registers c
LEFT JOIN (
    SELECT cash_register_id,
           SUM(amount) FILTER (WHERE transaction_type = 'IN')  AS cash_in,
           SUM(amount) FILTER (WHERE transaction_type = 'OUT') AS cash_out
    FROM financial_transactions
    WHERE status = 'VERIFIED' AND payment_method = 'EFECTIVO' AND cash_register_id IS NOT NULL
    GROUP BY cash_register_id
) m ON m.cash_register_id = c.id;

-- Vuelto calculado en efectivo
CREATE VIEW v_financial_cash_change AS
SELECT id AS financial_transaction_id, cash_given - amount AS cash_change
FROM financial_transactions
WHERE cash_given IS NOT NULL;
