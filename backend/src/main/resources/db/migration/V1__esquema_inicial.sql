    CONSTRAINT fk_movements_variant FOREIGN KEY (variant_id)
        REFERENCES product_variants (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_sale_detail FOREIGN KEY (sale_detail_id, variant_id)
        REFERENCES sale_details (id, variant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_order_detail FOREIGN KEY (order_detail_id, variant_id)
        REFERENCES order_details (id, variant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_purchase_detail FOREIGN KEY (purchase_detail_id, variant_id)
        REFERENCES purchase_details (id, variant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_return_detail FOREIGN KEY (sale_return_detail_id, variant_id)
        REFERENCES sale_return_details (id, variant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_movements_reversal FOREIGN KEY (reversal_of_id, variant_id)
        REFERENCES inventory_movements (id, variant_id) ON DELETE RESTRICT,
