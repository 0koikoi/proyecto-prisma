-- Un registro = un turno de caja física.
CREATE TABLE cash_registers (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    opened_by     bigint        NOT NULL,
    closed_by     bigint,
    opened_at     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at     timestamptz,
    initial_cash  numeric(12,2) NOT NULL,
    expected_cash numeric(12,2),
    counted_cash  numeric(12,2),
    status        varchar(10)   NOT NULL DEFAULT 'OPEN',
    notes         text,
    cash_difference numeric(12,2) GENERATED ALWAYS AS (counted_cash - expected_cash) STORED,
    CONSTRAINT pk_cash_registers PRIMARY KEY (id),
    CONSTRAINT fk_cash_registers_opened_by FOREIGN KEY (opened_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_registers_closed_by FOREIGN KEY (closed_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cash_registers_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT ck_cash_registers_initial CHECK (initial_cash >= 0 AND initial_cash <> 'NaN'),
    CONSTRAINT ck_cash_registers_counted CHECK (counted_cash IS NULL OR (counted_cash >= 0 AND counted_cash <> 'NaN')),
    CONSTRAINT ck_cash_registers_expected CHECK (expected_cash IS NULL OR expected_cash <> 'NaN'),
    CONSTRAINT ck_cash_registers_open_fields CHECK (
        status <> 'OPEN'
        OR (closed_by IS NULL AND closed_at IS NULL AND expected_cash IS NULL AND counted_cash IS NULL)
    ),
    CONSTRAINT ck_cash_registers_closed_fields CHECK (
        status <> 'CLOSED'
        OR (closed_by IS NOT NULL AND closed_at IS NOT NULL
            AND expected_cash IS NOT NULL AND counted_cash IS NOT NULL
            AND closed_at >= opened_at)
    )
);

-- Una sola caja física: máximo un turno OPEN a la vez.
CREATE UNIQUE INDEX uq_cash_registers_single_open
    ON cash_registers ((1)) WHERE status = 'OPEN';

CREATE INDEX ix_cash_registers_opened_by ON cash_registers (opened_by);
CREATE INDEX ix_cash_registers_closed_by ON cash_registers (closed_by);

