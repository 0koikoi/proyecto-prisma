-- Extensiones útiles para búsqueda difusa en catálogo (RF07, RNF02)
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------------
-- 0. Utilidades
-- ---------------------------------------------------------------------

-- updated_at se actualiza en cada UPDATE, no solo al insertar.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------
-- 1. Acceso · Auth / Settings
-- ---------------------------------------------------------------------

CREATE TABLE users (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY,
    username      varchar(50)  NOT NULL,
    password_hash varchar(255) NOT NULL,
    full_name     varchar(100) NOT NULL,
    role          varchar(20)  NOT NULL,
    is_active     boolean      NOT NULL DEFAULT true,
    created_at    timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'VENDEDOR')),
    CONSTRAINT ck_users_username_not_blank CHECK (btrim(username) <> ''),
    CONSTRAINT ck_users_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_users_full_name_not_blank CHECK (btrim(full_name) <> '')
);

-- Un solo índice único funcional (no se duplica con UNIQUE(username)).
CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

