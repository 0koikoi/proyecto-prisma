CREATE INDEX ix_order_details_variant ON order_details (variant_id);

CREATE TABLE inventory_reservations (
    order_detail_id bigint      NOT NULL,
    status          varchar(15) NOT NULL DEFAULT 'ACTIVE',
    created_by      bigint      NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at        timestamptz,
    CONSTRAINT pk_inventory_reservations PRIMARY KEY (order_detail_id),
    CONSTRAINT fk_reservations_order_detail FOREIGN KEY (order_detail_id)
        REFERENCES order_details (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservations_status CHECK (status IN ('ACTIVE', 'CONSUMED', 'RELEASED')),
    CONSTRAINT ck_reservations_ended CHECK (
        (status = 'ACTIVE' AND ended_at IS NULL)
        OR (status <> 'ACTIVE' AND ended_at IS NOT NULL AND ended_at >= created_at)
    )
);

CREATE TABLE order_status_history (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY,
    order_id    bigint      NOT NULL,
    changed_by  bigint      NOT NULL,
    from_status varchar(20),
    to_status   varchar(20) NOT NULL,
    changed_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason      text,
    CONSTRAINT pk_order_status_history PRIMARY KEY (id),
    CONSTRAINT fk_order_history_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_history_changed_by FOREIGN KEY (changed_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_history_to_status CHECK (
        to_status IN ('PENDING', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT ck_order_history_from_status CHECK (
        from_status IS NULL
        OR from_status IN ('PENDING', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT ck_order_history_creation CHECK (from_status IS NOT NULL OR to_status = 'PENDING'),
    CONSTRAINT ck_order_history_changed CHECK (from_status IS DISTINCT FROM to_status),
    CONSTRAINT ck_order_history_reason CHECK (reason IS NULL OR btrim(reason) <> '')
);

CREATE INDEX ix_order_history_order ON order_status_history (order_id, changed_at, id);
CREATE UNIQUE INDEX uq_order_history_creation
    ON order_status_history (order_id) WHERE from_status IS NULL;

