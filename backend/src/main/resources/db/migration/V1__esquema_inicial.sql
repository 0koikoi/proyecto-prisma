    CONSTRAINT fk_sales_cash_register FOREIGN KEY (cash_register_id)
        REFERENCES cash_registers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_sales_ticket_number UNIQUE (ticket_number),
    CONSTRAINT uq_sales_request_key UNIQUE (request_key),
    CONSTRAINT ck_sales_ticket_not_blank CHECK (btrim(ticket_number) <> ''),
    CONSTRAINT ck_sales_customer_not_blank CHECK (customer_name IS NULL OR btrim(customer_name) <> ''),
    CONSTRAINT ck_sales_status CHECK (status IN ('CONFIRMED', 'VOIDED')),
    CONSTRAINT ck_sales_discount CHECK (discount >= 0 AND discount <> 'NaN')
);

CREATE INDEX ix_sales_cash_register ON sales (cash_register_id);
CREATE INDEX ix_sales_created_at ON sales (created_at);
CREATE INDEX ix_sales_created_by ON sales (created_by);

CREATE TABLE sale_details (
    id         bigint        GENERATED BY DEFAULT AS IDENTITY,
