    CONSTRAINT ck_sale_details_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sale_details_amounts CHECK (
        unit_price >= 0 AND unit_price <> 'NaN' AND unit_cost >= 0 AND unit_cost <> 'NaN'
    )
);

CREATE INDEX ix_sale_details_variant ON sale_details (variant_id);

