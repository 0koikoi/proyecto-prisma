CREATE INDEX ix_products_name_trgm ON products USING gin (name gin_trgm_ops);

CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Unidad vendible física: producto + talla + color.
-- Para artículos sin talla o color usar etiquetas canónicas: 'UNICA' y 'SIN_COLOR'.
CREATE TABLE product_variants (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY,
    product_id      bigint        NOT NULL,
    sku             varchar(50)   NOT NULL,
    barcode         varchar(50),
    size_label      varchar(30)   NOT NULL,
    color_label     varchar(50)   NOT NULL,
    cost_price      numeric(14,4) NOT NULL,
    sale_price      numeric(12,2) NOT NULL,
    current_stock   integer       NOT NULL DEFAULT 0,
    min_stock_alert integer       NOT NULL DEFAULT 3,
    is_active       boolean       NOT NULL DEFAULT true,
    version         bigint        NOT NULL DEFAULT 0,
    created_at      timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_product_variants PRIMARY KEY (id),
    CONSTRAINT fk_variants_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT uq_variants_sku UNIQUE (sku),
    CONSTRAINT uq_variants_barcode UNIQUE (barcode),
    CONSTRAINT uq_variants_product_size_color UNIQUE (product_id, size_label, color_label),
    CONSTRAINT ck_variants_sku_not_blank CHECK (btrim(sku) <> ''),
    CONSTRAINT ck_variants_barcode_not_blank CHECK (barcode IS NULL OR btrim(barcode) <> ''),
    CONSTRAINT ck_variants_size_not_blank CHECK (btrim(size_label) <> ''),
    CONSTRAINT ck_variants_color_not_blank CHECK (btrim(color_label) <> ''),
    CONSTRAINT ck_variants_stock CHECK (current_stock >= 0),
    CONSTRAINT ck_variants_min_stock CHECK (min_stock_alert >= 0),
    CONSTRAINT ck_variants_cost CHECK (cost_price >= 0 AND cost_price <> 'NaN'),
    CONSTRAINT ck_variants_price CHECK (sale_price > 0 AND sale_price <> 'NaN'),
    CONSTRAINT ck_variants_version CHECK (version >= 0)
);

CREATE INDEX ix_product_variants_product ON product_variants (product_id);

CREATE TRIGGER trg_variants_updated_at
    BEFORE UPDATE ON product_variants
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

