    CONSTRAINT ck_movements_reversal_not_self CHECK (reversal_of_id IS NULL OR reversal_of_id <> id),
    CONSTRAINT ck_movements_reason CHECK (reason IS NULL OR btrim(reason) <> ''),
    CONSTRAINT ck_movements_type_origin CHECK (
        movement_type IN ('PURCHASE_RECEIPT', 'POS_SALE', 'ORDER_DISPATCH', 'RETURN', 'ADJUSTMENT', 'REVERSAL')
        AND (
            (movement_type = 'PURCHASE_RECEIPT'
                AND purchase_detail_id IS NOT NULL
                AND sale_detail_id IS NULL AND order_detail_id IS NULL AND sale_return_detail_id IS NULL AND reversal_of_id IS NULL
                AND quantity > 0)
            OR (movement_type = 'POS_SALE'
                AND sale_detail_id IS NOT NULL
                AND purchase_detail_id IS NULL AND order_detail_id IS NULL AND sale_return_detail_id IS NULL AND reversal_of_id IS NULL
                AND quantity < 0)
            OR (movement_type = 'ORDER_DISPATCH'
                AND order_detail_id IS NOT NULL
                AND purchase_detail_id IS NULL AND sale_detail_id IS NULL AND sale_return_detail_id IS NULL AND reversal_of_id IS NULL
                AND quantity < 0)
            OR (movement_type = 'RETURN'
                AND sale_return_detail_id IS NOT NULL
                AND purchase_detail_id IS NULL AND sale_detail_id IS NULL AND order_detail_id IS NULL AND reversal_of_id IS NULL
                AND quantity > 0)
            OR (movement_type = 'ADJUSTMENT'
                AND purchase_detail_id IS NULL AND sale_detail_id IS NULL AND order_detail_id IS NULL
                AND sale_return_detail_id IS NULL AND reversal_of_id IS NULL
                AND reason IS NOT NULL)
            OR (movement_type = 'REVERSAL'
                AND reversal_of_id IS NOT NULL
                AND purchase_detail_id IS NULL AND sale_detail_id IS NULL AND order_detail_id IS NULL
                AND sale_return_detail_id IS NULL
                AND reason IS NOT NULL)
        )
    )
);

